import type {
  JobWorkflowState,
  WorkflowShadowProposal,
  WorkflowShadowView,
} from "@workspace/api-zod";
import type { jobsTable } from "@workspace/db";

type Job = Pick<
  typeof jobsTable.$inferSelect,
  "id" | "status" | "recruitingMode" | "internalMobility"
>;
type State = Pick<
  JobWorkflowState,
  "briefHash" | "jobApproved" | "journeys" | "workflows" | "canApprove"
>;

const steps: Record<string, { title: string; checks: string[] }> = {
  screening: {
    title: "Propose requisition-specific screening",
    checks: [
      "Approved ICP and fair, PII-redacted scoring input",
      "Approved model/provider and reserved budget before any paid screening",
    ],
  },
  verification: {
    title: "Propose verification review",
    checks: [
      "Candidate permission and lawful verification sources",
      "Approved provider and reserved budget before any external lookup",
    ],
  },
  engagement: {
    title: "Propose outreach for human review",
    checks: [
      "Current opt-out/privacy and contact-conflict checks",
      "Approved claims, sender identity and requisition-specific send authority",
      "Duplicate-send prevention at dispatch time",
    ],
  },
  ai_interview: {
    title: "Propose AI interview preparation",
    checks: [
      "Current session-specific AI consent",
      "Approved questions, language, model and reserved budget",
      "Separate authority for invitation, scheduling and interview execution",
    ],
  },
  human_interview: {
    title: "Propose human interview coordination",
    checks: [
      "Human interviewer assignment and candidate agreement",
      "Calendar permission and confirmed availability",
      "Explicit booking, reminder and rescheduling authority",
    ],
  },
  evaluation_review: {
    title: "Request human evaluation review",
    checks: [
      "Real assessment evidence, not manual notes treated as AI scores",
      "Separate approval before sharing an evaluation with another party",
    ],
  },
  hiring_decision: {
    title: "Request the final human hiring decision",
    checks: [
      "Current permitted human approver",
      "Explicit human decision in the existing assisted hiring workflow; no inferred stage change",
    ],
  },
};
const interviewSteps: Record<string, string[]> = {
  ai: ["ai_interview"],
  human: ["human_interview"],
  ai_then_human: ["ai_interview", "human_interview"],
  human_then_ai: ["human_interview", "ai_interview"],
};
const base = (id: string): WorkflowShadowProposal => ({
  id,
  scope: "requisition",
  workflowId: null,
  candidateId: null,
  candidateName: null,
  journeyVersion: null,
  workflowRevision: null,
  nextStepKey: null,
  title: "",
  disposition: "blocked",
  explanation: "",
  reasons: [],
  requiredChecks: [],
  completedSteps: 0,
  evidenceSource: "manual_workflow_notes",
  executionAllowed: false,
});

/** Pure rules over already-authorized, currently privacy-sealed records. No I/O or writes. */
export function buildWorkflowShadow(
  job: Job,
  state: State,
  generatedAt = new Date().toISOString(),
): WorkflowShadowView {
  const approved = state.journeys.find((j) => j.status === "approved" && !j.stale);
  const source = base(`requisition:${job.id}`);
  source.journeyVersion = approved?.version ?? null;
  source.nextStepKey = "internal_review";
  source.title = job.internalMobility
    ? "Propose this client's employee-only talent review"
    : "Propose internal-first known-talent review";
  source.explanation = job.internalMobility
    ? "Internal Mobility considers only current employees owned by this hiring client. It is not a generic internal pool or permission for external discovery."
    : "Review known nonemployees first. Internal review is advisory in the assisted flow; autonomous external discovery would require separately approved scope and budget.";
  if (!state.jobApproved) source.reasons.push("The requisition is not live and approved.");
  if (!approved) source.reasons.push("There is no approved journey for the current brief.");
  source.disposition = source.reasons.length ? "blocked" : "proposed";
  source.requiredChecks = [
    "Review available job-specific Intelligence Engine evidence; none is generated by this preview",
    job.internalMobility
      ? "Recheck current-employee status and ownership for this client"
      : "Recheck nonemployee scope; internal review remains advisory, not a new assisted-flow blocking gate",
    "Approved sourcing capability, explicit execution authority and reserved budget before external discovery",
  ];

  const proposals = [
    source,
    ...state.workflows.map((workflow): WorkflowShadowProposal => {
      const proposal = {
        ...base(`workflow:${workflow.id}`),
        scope: "candidate" as const,
        workflowId: workflow.id,
        candidateId: workflow.candidateId,
        candidateName: workflow.candidateName,
        journeyVersion: workflow.journeyVersion,
        workflowRevision: workflow.revision,
        completedSteps: workflow.steps.filter((s) => s.status === "completed").length,
      };
      if (workflow.status === "cancelled" || workflow.status === "completed") {
        return {
          ...proposal,
          disposition: "terminal",
          title: "No further work proposed",
          explanation: `This planned workflow is ${workflow.status}. Its evidence/history remain; no new actions or automatic reenrollment are proposed.`,
        };
      }
      const journey = state.journeys.find((j) => j.id === workflow.journeyId);
      if (!state.jobApproved) proposal.reasons.push("The requisition is not live and approved.");
      if (workflow.status === "paused") proposal.reasons.push("This planned workflow is paused.");
      if (!journey || journey.status !== "approved" || journey.version !== workflow.journeyVersion)
        proposal.reasons.push(
          "This workflow does not have its exact approved bound journey version.",
        );
      if (
        journey &&
        journey.interviewPath !== "recruiter_choice" &&
        journey.interviewPath !== workflow.interviewPath
      ) {
        proposal.reasons.push(
          "The candidate interview path does not match the bound approved journey.",
        );
      }
      if (workflow.stale || !journey || journey.stale || journey.briefHash !== state.briefHash) {
        proposal.reasons.push(
          "The bound brief is stale or unavailable. Renew approval and enroll explicitly; never silently reroute this candidate.",
        );
      }
      const next = workflow.steps.find((s) => s.status !== "completed");
      proposal.nextStepKey = next?.key ?? null;
      if (proposal.reasons.length)
        return {
          ...proposal,
          title: "Resolve workflow blockers first",
          explanation: "No next execution is proposed while these blockers remain.",
        };
      const pathSupported = Object.hasOwn(interviewSteps, workflow.interviewPath);
      const expectedKeys = pathSupported
        ? [
            "screening",
            "verification",
            "engagement",
            ...interviewSteps[workflow.interviewPath],
            "evaluation_review",
            "hiring_decision",
          ]
        : [];
      if (
        !next ||
        !Object.hasOwn(steps, next.key) ||
        next.status === "cancelled" ||
        !pathSupported ||
        workflow.steps.map((s) => s.key).join("|") !== expectedKeys.join("|") ||
        workflow.steps.some((s) => s.authority !== "human_review")
      ) {
        return {
          ...proposal,
          disposition: "review_required",
          title: "Review unsupported or inconsistent workflow state",
          explanation:
            "There is no supported next human-reviewed step. No progression or outcome is inferred.",
          requiredChecks: ["Human reconciliation of this workflow and its approved journey"],
        };
      }
      if (workflow.steps.some((s) => s.status === "completed" && !s.evidence?.trim())) {
        return {
          ...proposal,
          disposition: "review_required",
          title: "Review missing completion evidence",
          explanation:
            "A completed step lacks manual evidence. Do not treat the status alone as a verified assessment or permission to progress.",
          requiredChecks: ["Human reconciliation of missing evidence"],
        };
      }
      if (next.status === "review_required" || next.status === "failed") {
        return {
          ...proposal,
          disposition: "review_required",
          title: `Review or recover ${next.label.toLowerCase()}`,
          explanation: `The unresolved step is recorded as ${next.status}. Resolve the uncertainty or failure with a human; do not infer a rejection or skip to a later step.`,
          requiredChecks: [
            "Human review of the existing manual note",
            "Record corrected evidence explicitly before considering the next step",
          ],
        };
      }
      const action = steps[next.key];
      return {
        ...proposal,
        disposition:
          next.key === "hiring_decision" || next.key === "evaluation_review"
            ? "review_required"
            : "proposed",
        title: action.title,
        explanation: `${proposal.completedSteps} preceding step(s) have manual completion notes. ${next.label} is the first unresolved step in approved journey v${workflow.journeyVersion}; these notes are not AI scores or proof of a real assessment.`,
        reasons:
          next.key === "hiring_decision" && !state.canApprove
            ? [
                "Your role cannot record the final human decision. A permitted approver must review.",
              ]
            : [],
        requiredChecks: [
          "Explicit human checkpoint authority; the mode preset is not blanket permission",
          ...action.checks,
        ],
      };
    }),
  ];
  return {
    generatedAt: new Date(generatedAt),
    briefHash: state.briefHash,
    methodology: "deterministic_workflow_rules",
    recruitingMode: job.recruitingMode,
    sourcingScope: job.internalMobility
      ? "client_current_employees"
      : "known_nonemployees_then_permitted_external",
    autonomyExecutionEnabled: false,
    executionAllowed: false,
    modelCalls: 0,
    estimatedExecutionCost: null,
    costExplanation:
      "This read-only preview makes no model/provider calls or credit reservations. Future execution costs are not quoted or estimated here.",
    proposals,
  };
}
