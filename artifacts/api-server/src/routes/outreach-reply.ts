function renderConfirm(token: string, action: ReplyAction): string {
  const c = ACTION_COPY[action];
  return baseLayout(c.title, c.color, `
    <p style="margin:0 0 22px;font-size:15px;line-height:1.55;color:#4b5563;">${esc(c.body)}</p>
    <form method="POST" action="/api/outreach/reply/${esc(token)}" style="margin:0;">
      <button type="submit" style="display:inline-block;padding:12px 22px;border:0;border-radius:24px;font:500 15px/1 -apple-system,Segoe UI,Helvetica,Arial,sans-serif;color:#fff;background:${c.color};cursor:pointer;">${esc(c.cta)}</button>
    </form>
    <div style="margin-top:18px;font-size:12px;color:#9ca3af;">Not you? Just close this page — nothing has been changed yet.</div>
  `);
}

function renderResult(title: string, message: string, color: string): string {
  return baseLayout(title, color, `<p style="margin:0;font-size:15px;line-height:1.55;color:#4b5563;">${esc(message)}</p>`);
}

function renderError(title: string, message: string): string {
  return baseLayout(title, "#991b1b", `<p style="margin:0;font-size:15px;line-height:1.55;color:#4b5563;">${esc(message)}</p>`);
}

function baseLayout(title: string, accent: string, inner: string): string {
  return `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(title)}</title>
<style>
  body{margin:0;font-family:-apple-system,Segoe UI,Helvetica,Arial,sans-serif;background:#f9fafb;color:#1f2937;display:flex;align-items:center;justify-content:center;min-height:100vh;padding:24px;}
  .card{max-width:480px;width:100%;background:#fff;border-radius:14px;padding:36px 32px;box-shadow:0 4px 24px rgba(0,0,0,.06);text-align:center;box-sizing:border-box;}
  .bar{width:48px;height:4px;border-radius:2px;background:${accent};margin:0 auto 22px;}
  h1{margin:0 0 14px;font-size:22px;color:${accent};}
  .foot{margin-top:24px;font-size:12px;color:#9ca3af;}
</style></head>
<body><div class="card"><div class="bar"></div><h1>${esc(title)}</h1>${inner}<div class="foot">Lexy · AI Hiring Platform</div></div></body></html>`;
}

function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

