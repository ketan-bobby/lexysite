/**
 * routes/outreach-reply.ts — One-Click Email Reply Handler
 *
 * ─── What this file does ────────────────────────────────────────────────────
 * Handles the public URL that candidates land on when they click a quick-reply
 * button in an outreach email ("I'm interested" / "Not for this role" /
 * "Stop emailing me"). The token in the URL is verified by outreach-reply-tokens.ts
 * and then the appropriate action is applied atomically.
 *
 * ─── Two token namespaces ────────────────────────────────────────────────────
 *   GET /outreach/reply/:token      Enrollment tokens (campaign sequences)
 *     Resolves to an outreach_enrollments row. Actions applied:
 *       interested        → notifyRecruiterOfReply(classification=interested)
 *       not_interested_job → cancel enrollment + notifyRecruiter(not_interested)
 *       dnc               → cancel enrollment + recordRejection + doNotContact
 *
 *   GET /outreach/reply-msg/:token  Message tokens (orchestrator one-off emails)
 *     Resolves to an outreach_messages row. Same action cascade but stamped on
 *     the message row (repliedAt, replyAction) rather than the enrollment row.
 *
 * ─── Action mapping ──────────────────────────────────────────────────────────
 * QUICK_REPLY_TO_CLASSIFICATION maps token actions → ReplyClassification so
 * the recruiter notify logic is shared with the webhook inbound-email path.
 *
 * ─── DNC cascade ─────────────────────────────────────────────────────────────
 * dnc action calls recordRejection() (rejection record + optional email) and
 * then sets candidates.doNotContact = true. All open enrollments for the
 * candidate are cancelled at the same time so they receive no further outreach.
 *
 * ─── Called by ───────────────────────────────────────────────────────────────
 *   Email buttons generated by buildQuickReplyBlocks() in outreach-reply-tokens.ts
 *   Mounted at GET /api/outreach/reply/:token and /api/outreach/reply-msg/:token
 *   by routes/index.ts.
 */
